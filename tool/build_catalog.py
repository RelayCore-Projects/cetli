#!/usr/bin/env python3
"""Build the built-in catalog file of the app from the reviewed Obsidian note.

Run from the repository root:  python3 tool/build_catalog.py
Input:  docs/Katalógus – beépített tételek.md   (bullet lines; struck-through ones are skipped)
Output: assets/catalog/builtin_items.txt         (one item per line, A–Z)
"""
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / "docs/Katalógus – beépített tételek.md"
TARGET = ROOT / "assets/catalog/builtin_items.txt"


def main():
    names, seen = [], set()
    for line in SOURCE.read_text(encoding="utf-8").splitlines():
        m = re.match(r"^- (?!~~)(.+?)\s*$", line)
        if not m:
            continue
        name = re.sub(r"\s+", " ", m.group(1)).strip()
        key = name.lower()
        if key in seen:
            raise SystemExit(f"Duplicate item: {name}")
        seen.add(key)
        names.append(name)
    names.sort(key=str.lower)
    header = (
        "# Cetli built-in catalog – generated by tool/build_catalog.py, do not edit by hand.\n"
        "# Source: docs/Katalógus – beépített tételek.md\n"
    )
    TARGET.parent.mkdir(parents=True, exist_ok=True)
    TARGET.write_text(header + "\n".join(names) + "\n", encoding="utf-8")
    print(f"{len(names)} items written to {TARGET.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
